const key = "librarian-language";
let language = "ar";
try { if (localStorage.getItem(key) === "en") language = "en"; } catch {}

export function translate(arabic, english = dictionary.get(arabic) || arabic) {
  return language === "en" ? english : arabic;
}

export function languageCode() { return language; }

const textNodes = [];
const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest("script, style, noscript, svg")) continue;
  const original = node.nodeValue;
  const phrase = original.trim();
  if (dictionary.has(phrase)) textNodes.push({ node, original, phrase });
}
const attributes = [];
for (const element of document.querySelectorAll("[aria-label], [placeholder]")) {
  for (const name of ["aria-label", "placeholder"]) {
    const phrase = element.getAttribute(name);
    if (dictionary.has(phrase)) attributes.push({ element, name, phrase });
  }
}

const button = document.querySelector("#library-language");
function apply() {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "en" ? "ltr" : "rtl";
  for (const { node, original, phrase } of textNodes) {
    if (node.isConnected) node.nodeValue = original.replace(phrase, translate(phrase));
  }
  for (const { element, name, phrase } of attributes) element.setAttribute(name, translate(phrase));
  if (button) {
    button.textContent = language === "en" ? "العربية" : "English";
    button.lang = language === "en" ? "ar" : "en";
    button.setAttribute("aria-label", button.textContent);
  }
  document.dispatchEvent(new Event("library:language"));
}

if (button) {
  button.hidden = false;
  button.addEventListener("click", () => {
    language = language === "en" ? "ar" : "en";
    try { localStorage.setItem(key, language); } catch {}
    apply();
  });
}
apply();
