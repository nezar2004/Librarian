const originals = new WeakMap();
const attrs = new WeakMap();
function localize(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (!node.parentElement || node.parentElement.closest("script, style, noscript, svg, [data-no-translate]")) return;
    const saved = originals.get(node);
    const original = saved?.rendered === node.nodeValue ? saved.original : node.nodeValue;
    const phrase = original.trim();
    const count = phrase.match(/^(\d+) كتب مستعارة$/);
    const english = dictionary.get(phrase) ?? (count ? count[1] + " books on loan"
      : phrase.startsWith("مرحباً ") ? "Welcome, " + phrase.slice("مرحباً ".length)
      : phrase.startsWith("متوفر (") ? "Available " + phrase.slice("متوفر ".length)
      : phrase.startsWith("رقم الطالب: ") ? "Student ID: " + phrase.slice("رقم الطالب: ".length)
      : phrase);
    if (english === phrase) return;
    const parent = node.parentElement;
    if (parent.tagName === "OPTION" && !parent.hasAttribute("value")) parent.value = parent.text;
    const rendered = original.replace(phrase, translate(phrase, english));
    originals.set(node, { original, rendered });
    if (rendered !== node.nodeValue) node.nodeValue = rendered;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  for (const el of [node, ...node.querySelectorAll("[aria-label], [placeholder]")]) {
    if (el.id === "library-language") continue;
    const saved = attrs.get(el) || {};
    for (const name of ["aria-label", "placeholder"]) {
      const value = el.getAttribute(name);
      const original = saved[name]?.rendered === value ? saved[name].original : value;
      if (!dictionary.has(original)) continue;
      const rendered = translate(original);
      saved[name] = { original, rendered };
      if (value !== rendered) el.setAttribute(name, rendered);
    }
    attrs.set(el, saved);
  }
  const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) localize(walker.currentNode);
}

const button = document.querySelector("#library-language");
function apply() {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "en" ? "ltr" : "rtl";
  localize(document.documentElement);
  if (button) {
    button.textContent = language === "en" ? "العربية" : "English";
    button.lang = language === "en" ? "ar" : "en";
    button.setAttribute("aria-label", button.textContent);
  }
  document.dispatchEvent(new Event("library:language"));
}

